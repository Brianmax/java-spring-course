public class Cliente {
    int idCliente;
    String nombre;
    String apellido;
    String email;

    public Cliente(int idCliente, String nombre, String apellido, String email) {
        this.idCliente = idCliente;
        this.nombre = nombre;
        this.apellido = apellido;
        this.email = email;
    }

    public Cliente() {
    }
}
